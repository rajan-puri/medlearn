import { expect, test } from '@playwright/test'

test('home combobox works with only the keyboard', async ({ page }) => {
  await page.goto('/')
  const combobox = page.getByRole('combobox', { name: 'Keyword' })
  await combobox.focus()
  await expect(combobox).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(combobox).not.toHaveValue('')
  await combobox.press('Escape')
  await expect(combobox).toHaveAttribute('aria-expanded', 'false')
})

test('course tabs implement the ARIA keyboard pattern', async ({ page }) => {
  await page.goto('/courses/clinical-anatomy-in-practice')
  const about = page.getByRole('tab', { name: 'About' })
  await about.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Schedule' })).toBeFocused()
  await expect(page.getByRole('tab', { name: 'Schedule' })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: 'Reviews' })).toBeFocused()
  await page.keyboard.press('Home')
  await expect(about).toBeFocused()
})

test('enrollment dialog traps focus, closes with Escape, and returns focus', async ({ page }) => {
  await page.goto('/courses/clinical-anatomy-in-practice')
  const trigger = page.getByRole('button', { name: 'Enroll in course' })
  await trigger.focus()
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Confirm enrollment' })
  await expect(dialog).toBeVisible()
  await expect(dialog).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Confirm enrollment' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('invalid new-course form focuses a linked error summary', async ({ page }) => {
  await page.goto('/manage')
  const trigger = page.getByRole('button', { name: 'New course' })
  await trigger.focus()
  await trigger.press('Enter')
  await page.getByRole('button', { name: 'Create course' }).press('Enter')
  const summary = page.getByRole('alert')
  await expect(summary).toBeFocused()
  await expect(page.locator('#course-title')).toHaveAttribute('aria-invalid', 'true')
  await summary.getByRole('link', { name: /course title/i }).press('Enter')
  await expect(page.locator('#course-title')).toBeFocused()
})
